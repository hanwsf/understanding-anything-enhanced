#!/usr/bin/env node
/**
 * build-final-graph.mjs
 *
 * Converts batch structure JSON output (from extract-structure.mjs)
 * into a fully-validated knowledge graph (nodes + edges + layers + tour).
 *
 * This is the deterministic fallback that the /understand pipeline needs
 * when the LLM file-analyzer agent cannot produce valid GraphNode/GraphEdge objects.
 *
 * Usage:
 *   node build-final-graph.mjs <projectRoot> <intermediateDir>
 *
 * Inputs:
 *   <projectRoot>         Absolute path to the project root
 *   <intermediateDir>     Path to .understand-anything/intermediate/
 *                         (expects batch-N-structure.json and scan-result.json)
 *
 * Output:
 *   <intermediateDir>/knowledge-graph.json
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join, resolve, dirname, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

// ── CLI args ─────────────────────────────────────────────────────────────────
const [,, projectRoot, intermediateDir] = process.argv;
if (!projectRoot || !intermediateDir) {
  process.stderr.write(
    'Usage: node build-final-graph.mjs <projectRoot> <intermediateDir>\n'
  );
  process.exit(1);
}

const PROJECT_ROOT = resolve(projectRoot);
const OUTPUT_DIR = resolve(PROJECT_ROOT, '.understand-anything');
const INTERMEDIATE = resolve(intermediateDir);

// ── Helpers ───────────────────────────────────────────────────────────────────
function readJson(p) {
  return JSON.parse(readFileSync(p, 'utf8'));
}

function dumpWarnings(msg) {
  process.stderr.write(`[build-final-graph] ${msg}\n`);
}

// ── Project metadata (required by GraphNodeSchema / ProjectMetaSchema) ────────
function getProjectMetadata() {
  // Try to get from scan-result.json (written by project-scanner agent)
  let name = basename(PROJECT_ROOT);
  let description = '';
  let languages = [];
  let frameworks = [];
  let gitCommitHash = '';
  try {
    const projMeta = readJson(join(INTERMEDIATE, '..', 'meta.json'));
    if (projMeta) {
      name = projMeta.name || name;
      description = projMeta.description || '';
      languages = projMeta.languages || [];
      frameworks = projMeta.frameworks || [];
      gitCommitHash = projMeta.gitCommitHash || '';
    }
  } catch (_) { /* meta.json not available */ }
  // Try scan-result.json as fallback
  if (!description && scan && scan.project) {
    name = scan.project.name || name;
    description = scan.project.description || '';
    languages = scan.project.languages || languages;
    frameworks = scan.project.frameworks || frameworks;
  }
  // Get git commit hash
  if (!gitCommitHash) {
    try {
      gitCommitHash = execSync('git rev-parse HEAD', { cwd: PROJECT_ROOT, encoding: 'utf-8' }).trim();
    } catch (_) { /* not a git repo */ }
  }
  return {
    name: name || 'Unknown Project',
    languages,
    frameworks,
    description: description || 'Knowledge graph generated by Understand-Anything',
    analyzedAt: new Date().toISOString(),
    gitCommitHash,
  };
}

// ── Load scan result ──────────────────────────────────────────────────────────
let scan;
try {
  scan = readJson(join(INTERMEDIATE, 'scan-result.json'));
} catch (e) {
  dumpWarnings('Warning: scan-result.json not found — proceeding without import edges');
  scan = { files: [] };
}

// ── Collect all batch structure results ───────────────────────────────────────
const allResults = [];
let batchIdx = 1;
while (true) {
  const p = join(INTERMEDIATE, `batch-${batchIdx}-structure.json`);
  if (!existsSync(p)) break;
  try {
    const data = JSON.parse(readFileSync(p, 'utf8'));
    if (data.results && Array.isArray(data.results)) {
      allResults.push(...data.results);
    }
  } catch (e) {
    dumpWarnings(`Warning: could not parse batch-${batchIdx}-structure.json`);
  }
  batchIdx++;
}

if (allResults.length === 0) {
  process.stderr.write(
    '[build-final-graph] Error: no batch structure files found in intermediate/\n'
  );
  process.exit(1);
}

console.log(`[build-final-graph] Loaded ${allResults.length} analyzed files from ${batchIdx - 1} batches`);

const fileMap = new Map();
for (const r of allResults) fileMap.set(r.path, r);

// ── Graph primitives ─────────────────────────────────────────────────────────
const nodes = [];
const edges = [];
const nodeIds = new Set();
const dirNodes = new Map();

function addNode(id, type, name, extra = {}) {
  if (nodeIds.has(id)) return nodes.find(n => n.id === id) || null;
  const node = {
    id, type, name,
    path:        extra.path        || '',
    summary:     extra.summary     || (type === 'file' ? `${name}` : `${type}: ${name}`),
    tags:        extra.tags        || [],
    language:    extra.language    || 'unknown',
    layer:       extra.layer       || 'default',
    complexity:  extra.complexity  || 'medium',
    ...extra,
  };
  nodes.push(node);
  nodeIds.add(id);
  return node;
}

function addEdge(source, target, type, extra = {}) {
  if (source && target) {
    // Deduplicate: skip if an edge with same (source, target, type) already exists
    const dup = (type === 'calls' || type === 'contains' || type === 'imports')
      && edges.some(e => e.source === source && e.target === target && e.type === type);
    if (dup) return;
    edges.push({
      source,
      target,
      type,
      weight: extra.weight ?? 0.5,
      direction: extra.direction ?? 'forward',
      ...extra,
    });
  }
}

// ── Layer assignment ──────────────────────────────────────────────────────────
function getLayer(fp, language, category) {
  if (category === 'config') return '配置层';
  if (category === 'docs')   return '文档层';
  if (category === 'infra')  return '基础设施层';
  if (fp.startsWith('.github/'))                        return 'CI/CD层';
  if (fp.startsWith('scripts/kb/'))                    return '知识库层';
  if (fp.startsWith('scripts/web/'))                   return 'Web服务层';
  if (fp.startsWith('scripts/orchestrate/'))           return '编排调度层';
  if (fp.startsWith('scripts/executor/'))              return '执行引擎层';
  if (fp.startsWith('scripts/llm/'))                   return 'LLM接入层';
  if (fp.startsWith('scripts/context/'))               return '上下文管理层';
  if (fp.startsWith('scripts/security/'))              return '安全层';
  if (fp.startsWith('scripts/utils/'))                 return '工具函数层';
  if (fp.startsWith('scripts/validation/'))            return '校验层';
  if (fp.startsWith('scripts/alerts/'))                return '告警层';
  if (fp.startsWith('scripts/cache/'))                 return '缓存层';
  if (fp.startsWith('scripts/clients/'))               return '客户端层';
  if (fp.startsWith('scripts/tools/'))                 return '工具服务层';
  if (fp.startsWith('__admin/'))                       return '管理工具层';
  if (fp.startsWith('tests/'))                         return '测试层';
  if (fp.startsWith('scripts/'))                       return '代码执行层';
  if (fp.startsWith('assets/'))                        return '资源层';
  if (fp.startsWith('docs/'))                          return '文档层';
  return '根层';
}

// ── Directory node management ─────────────────────────────────────────────────
function getDirNode(dirPath) {
  if (dirNodes.has(dirPath)) return dirNodes.get(dirPath);
  const parts = dirPath.split('/');
  const name = parts[parts.length - 1] || dirPath;
  const id = 'dir:' + dirPath;
  // Use 'module' type (valid GraphNodeSchema enum) instead of 'directory'
  addNode(id, 'module', name, {
    path: dirPath,
    summary: `目录 ${name}`,
    tags: ['dir', ...(dirPath === name ? [name] : [])],
    layer: getLayer(dirPath, 'meta', 'dir'),
    complexity: 'simple',  // schema enum: simple | moderate | complex — no 'low'
  });
  dirNodes.set(dirPath, id);
  return id;
}

// ── Import extraction ────────────────────────────────────────────────────────
function extractImports(content) {
  const imports = [];
  if (!content) return imports;
  for (const line of content.split('\n')) {
    const t = line.trim();
    let m = t.match(/^from\s+([\w.]+)\s+import/);
    if (m) { imports.push(m[1]); continue; }
    m = t.match(/^import\s+([\w.]+)/);
    if (m) imports.push(m[1]);
  }
  return imports;
}

// ── Pre-create all intermediate directory nodes ───────────────────────────────
for (const result of allResults) {
  const parts = result.path.split('/');
  let current = '';
  for (let i = 0; i < parts.length - 1; i++) {
    current = current ? current + '/' + parts[i] : parts[i];
    getDirNode(current);
  }
}

// ── Build graph from each file ────────────────────────────────────────────────
const processedFiles = new Set();

for (const result of allResults) {
  const fp = result.path;
  if (processedFiles.has(fp)) continue;
  processedFiles.add(fp);

  const lang       = result.language    || 'unknown';
  const category   = result.fileCategory || 'other';
  const lines      = result.totalLines || 0;
  const layer      = getLayer(fp, lang, category);
  const nodeId     = 'file:' + fp;
  const name       = basename(fp);

  // Complexity: schema enum is simple | moderate | complex (no 'very-complex')
  // Thresholds (matches scan-project.mjs style):
  //   0–100   → simple,  100–300 → moderate,  >300 → complex
  let complexity = 'simple';
  if (lines > 100) complexity = 'moderate';
  if (lines > 300) complexity = 'complex';

  // Tags
  const tags = [lang, category];
  if (fp.includes('auth'))           tags.push('认证');
  if (fp.includes('kb') || fp.includes('knowledge')) tags.push('知识库');
  if (fp.includes('executor'))      tags.push('执行器');
  if (fp.includes('web'))           tags.push('web服务');
  if (fp.includes('orchestrate'))   tags.push('编排');
  if (fp.includes('security'))      tags.push('安全');
  if (fp.includes('llm'))           tags.push('LLM');
  if (fp.includes('test'))          tags.push('测试');
  if (fp.includes('mcp'))           tags.push('MCP');

  // Summary
  const summary = lang === 'python' && category === 'code'
    ? `${name.replace(/\.\w+$/, '')} — ${(result.classes || []).length} 类, `
      + `${(result.exports || []).length} 导出, ${(result.callGraph || []).length} 调用关系`
    : `${category}: ${name}`;

  // File node
  addNode(nodeId, 'file', name, {
    path: fp, summary, tags, language: lang, layer, complexity,
    sizeLines: lines, fileCategory: category,
  });

  // ── Class nodes ──
  // extract-structure.mjs emits objects {name, startLine, endLine, methods, properties}
  // NOT plain strings — handle both formats defensively
  const classes = (result.classes || []);
  for (const cls of classes) {
    const clsName = typeof cls === 'string' ? cls : (cls.name || String(cls));
    const classId = `class:${fp}:${clsName}`;
    addNode(classId, 'class', clsName, {
      path: fp, summary: `类 ${clsName}`,
      tags: ['class', ...tags], language: lang, layer, complexity: 'simple',
      parentFile: nodeId,
    });
    // Use 'contains' (schema-valid enum) instead of 'defined-in'
    addEdge(classId, nodeId, 'contains');
  }

  // ── Export / function nodes ──
  // extract-structure.mjs emits objects {name, line, isDefault}
  // NOT plain strings — handle both formats defensively
  const exports = (result.exports || []);
  for (const exp of exports) {
    const expName = typeof exp === 'string' ? exp : (exp.name || String(exp));
    const expId = `export:${fp}:${expName}`;
    addNode(expId, 'function', expName, {
      path: fp, summary: `函数 ${expName}`,
      tags: ['function', ...tags], language: lang, layer, complexity: 'simple',
      parentFile: nodeId,
    });
    addEdge(expId, nodeId, 'contains');
  }
// Pre-process callGraph to build function map (incl. private/internal functions)
const functionMap = new Map();
const skipRe = /^tests[\/]|[\/]test_/;
for (const r of allResults) {
  if (skipRe.test(r.path)) continue;
  for (const c of (r.callGraph || [])) {
    if (!c.caller) continue;
    const fn = String(c.caller).split('.')[0].trim();
    if (!fn || fn.startsWith('.')) continue;
    const key = r.path + '::' + fn;
    if (!functionMap.has(key)) functionMap.set(key, { file: r.path, name: fn });
  }
}
// Create missing function nodes (non-exported functions referenced in callGraph)
const addedFnIds = new Set();
for (const [key, fi] of functionMap) {
  const fid = 'export:' + fi.file + ':' + fi.name;
  if (nodeIds.has(fid)) continue;
  const r2 = allResults.find(x => x.path === fi.file);
  if (!r2) continue;
  const fnLang = r2.language || 'unknown';
  addNode(fid, 'function', fi.name, {
    path: fi.file, summary: '函数 ' + fi.name,
    tags: ['function', fnLang, (r2.fileCategory || 'code')],
    language: fnLang, layer: getLayer(fi.file, fnLang, r2.fileCategory || 'code'),
    complexity: 'simple',
  });
  addedFnIds.add(fid);
  // Add contains edge from this function to its parent file
  addEdge(fid, 'file:' + fi.file, 'contains');
}
const callGraph = (result.callGraph || []);
for (const call of callGraph) {
  if (!call.caller || !call.callee) continue;
  if (fp.startsWith('tests/') || fp.includes('/test_')) continue;
  const calleeName = String(call.callee).split('.')[0].split('(')[0].trim();
  if (!calleeName || calleeName === call.caller) continue;
  const callerId = 'export:' + fp + ':' + call.caller;
  // Only resolve same-file calls — cross-file name-matching is unreliable
  // without import-aware resolution (same function name in different files
  // does not mean they're the same function).
  const sameFileCalleeId = 'export:' + fp + ':' + calleeName;
  if (nodeIds.has(callerId) && nodeIds.has(sameFileCalleeId)) {
    addEdge(callerId, sameFileCalleeId, 'calls');
  }
}
  // ── Import edges (Python source) ──────────────────────────────────────────
  if (lang === 'python' && category === 'code') {
    try {
      const fullPath = join(PROJECT_ROOT, fp);
      if (existsSync(fullPath)) {
        const sourceContent = readFileSync(fullPath, 'utf-8');
        const imports = extractImports(sourceContent);
        for (const imp of imports) {
          const modBase = imp.split('.')[0];
          for (const [otherPath] of fileMap) {
            if (otherPath === fp) continue;
            const otherBase  = basename(otherPath, extname(otherPath));
            const otherMod   = otherPath.replace(/\.py$/, '').replace(/\//g, '.');
            const impPath = imp.replace(/\./g, '/') + '.py';
            if (modBase === otherBase || imp === otherMod ||
                otherPath.endsWith('/' + impPath) || otherPath === impPath) {
              addEdge(nodeId, 'file:' + otherPath, 'imports');
              break;
            }
          }
        }
      }
    } catch (e) { /* skip */ }
  }

  // ── Link file → parent directory ──────────────────────────────────────────
  const parts = fp.split('/');
  if (parts.length > 1) {
    const parentDir = parts.slice(0, -1).join('/');
    if (parentDir) {
      const dirId = getDirNode(parentDir);
      addEdge(nodeId, dirId, 'contains');
    }
  }
}

// ── Tour (guided walkthrough) ────────────────────────────────────────────────
const fileNodes = nodes.filter(n => n.type === 'file');
const sampleFiles = fileNodes.slice(0, 6);
const tour = [
  { order: 1, title: '项目概览', description: '浏览项目的整体架构和主要模块。', nodeIds: sampleFiles.slice(0, 2).map(n => n.id) },
  { order: 2, title: '核心入口', description: '找到项目的主要入口文件和启动流程。', nodeIds: [sampleFiles[2]?.id, sampleFiles[3]?.id].filter(Boolean) },
  { order: 3, title: '功能模块', description: '探索项目的核心功能模块和关键组件。', nodeIds: [sampleFiles[4]?.id, sampleFiles[5]?.id].filter(Boolean) },
];

// ── Layers ────────────────────────────────────────────────────────────────────
const layerMap = new Map();
for (const n of nodes) {
  if (!layerMap.has(n.layer)) layerMap.set(n.layer, []);
  layerMap.get(n.layer).push(n.id);
}
const layers = Array.from(layerMap.entries()).map(([name, ids], idx) => ({
  id: 'layer:' + (name.toLowerCase().replace(/[^a-z0-9]/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '') || ('layer-' + idx)),
  name: name,
  description: name + ' — ' + ids.length + ' nodes',
  nodeIds: ids,
}));
// ── Assemble and write ────────────────────────────────────────────────────────
console.log(`[build-final-graph] Total nodes: ${nodes.length}, edges: ${edges.length}`);
const typeCounts = nodes.reduce((acc, n) => { acc[n.type] = (acc[n.type] || 0) + 1; return acc; }, {});
console.log(`[build-final-graph] Node types: ${JSON.stringify(typeCounts)}`);

const projectMeta = getProjectMetadata();

const kg = {
 version:  '1.0.0',
 kind:     'codebase',
 project:  projectMeta,
 nodes, edges, layers, tour,
 projectRoot:   PROJECT_ROOT,
 fileCount:     processedFiles.size,
 nodeCount:     nodes.length,
 edgeCount:     edges.length,
};

const outPath = join(OUTPUT_DIR, 'knowledge-graph.json');
writeFileSync(outPath, JSON.stringify(kg, null, 2), 'utf-8');
console.log(`[build-final-graph] Saved knowledge-graph.json (${(JSON.stringify(kg).length / 1024).toFixed(1)} KB)`);

// ── Stats ─────────────────────────────────────────────────────────────────────
const edgeTypeCounts = {};
edges.forEach(e => { edgeTypeCounts[e.type] = (edgeTypeCounts[e.type] || 0) + 1; });
console.log(`[build-final-graph] Edge types:`, JSON.stringify(edgeTypeCounts));
